#!/usr/bin/env python3
"""gen_tramp.py: writes gli_tramp_gen.h, one arm64 (Mach-O) trampoline per GLI slot: count the call, then `br` to the saved original with EVERY argument register and the
stack untouched (only x16/x17, the intra-procedure scratch registers, are used). Used by SWEETGL_HIST=1 (call-count histogram, research 61). Usage: gen_tramp.py [N]"""
import sys
n = int(sys.argv[1]) if len(sys.argv) > 1 else 1036
out = ['/* generated by gen_tramp.py: do not edit */', '#if defined(__aarch64__) && defined(__APPLE__)', '#define SGL_HAVE_TRAMP 1', '__asm__(', '".text\\n"', '".p2align 2\\n"']
for i in range(n):
    off = i * 8
    out.append('"_sgl_tramp_%d:\\n"' % i)
    out.append('" adrp x16, _sgl_cnt@PAGE\\n add x16, x16, _sgl_cnt@PAGEOFF\\n ldr x17, [x16, #%d]\\n add x17, x17, #1\\n str x17, [x16, #%d]\\n"' % (off, off))
    out.append('" adrp x16, _sgl_orig@PAGE\\n add x16, x16, _sgl_orig@PAGEOFF\\n ldr x16, [x16, #%d]\\n br x16\\n"' % off)
out.append('".data\\n"')
out.append('".p2align 3\\n"')
out.append('".globl _sgl_tramps\\n"')
out.append('"_sgl_tramps:\\n"')
for i in range(n):
    out.append('" .quad _sgl_tramp_%d\\n"' % i)
out.append(');')
out.append('#endif')
open('gli_tramp_gen.h', 'w').write('\n'.join(out) + '\n')
